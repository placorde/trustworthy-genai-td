import csv
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main():
    rule = json.loads((ROOT / "routing" / "routing-rule.json").read_text(encoding="utf-8"))
    rates = json.loads((ROOT / "routing" / "family-rates-td1.json").read_text(encoding="utf-8"))
    with open(ROOT / "model-question-comparison-en.csv", newline="", encoding="utf-8") as f:
        cells = {(r["model_id"], r["case_id"]): r for r in csv.DictReader(f)}
    with open(ROOT / "reference-td1.csv", newline="", encoding="utf-8") as f:
        reference = {r["case_id"]: r["revenue_cents"] for r in csv.DictReader(f)}

    lines = ["# Quorum of the rule replayed on the TD1 traces", "",
             "Generated by `routing/quorum_check.py`. For each family, the three quorum members of",
             "`routing/routing-rule.json` vote with their final TD1 value (executed values only, an invalid or",
             "unavailable member stays in n without a vote), threshold k = 2 of n = 3; the reference is compared",
             "after the decision.", "",
             "| Family | Question | Values (members in order) | Decision | Reference | Outcome |", "|---|---|---|---|---|---|"]
    totals = Counter()
    for family, members in rule["quorum_members"].items():
        for case in rates["families"][family]["cases"]:
            values = [cells[(m, case)]["value_cents"] if cells[(m, case)]["status"] in ("correct", "incorrect") else None
                      for m in members]
            counts = Counter(v for v in values if v is not None)
            value, votes = counts.most_common(1)[0] if counts else (None, 0)
            consensus = votes >= 2
            ref = reference[case]
            outcome = "correct" if consensus and value == ref else ("abstention" if not consensus else "WRONG")
            totals[(family, outcome)] += 1
            shown = ", ".join(v if v is not None else "no vote" for v in values)
            lines.append(f"| {family} | {case} | {shown} | {'consensus ' + value + f' ({votes}/3)' if consensus else f'abstain (max {votes}/3)'} | {ref} | {outcome} |")
    lines += ["", "| Family | Correct | Abstention | Wrong |", "|---|---|---|---|"]
    for family in rule["quorum_members"]:
        lines.append(f"| {family} | {totals[(family, 'correct')]} | {totals[(family, 'abstention')]} | {totals[(family, 'WRONG')]} |")
    (ROOT / "routing" / "quorum-check-td1.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
