import argparse
import csv
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

SHORT = {"correct": "OK", "incorrect": "wrong", "sql_invalid": "invalid", "sql_rejected": "rejected",
         "access_error": "access", "not_executed": "not run"}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--comparison", type=Path, default=ROOT / "model-question-comparison-en.csv")
    parser.add_argument("--out", type=Path, default=ROOT / "results-pivot-td1.md")
    args = parser.parse_args()

    with open(args.comparison, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    models = list(dict.fromkeys(r["model_id"] for r in rows))
    cases = sorted({r["case_id"] for r in rows})
    cell = {(r["model_id"], r["case_id"]): r for r in rows}

    lines = ["# TD1 models x questions (pivot view)", "",
             f"Generated by `traces/pivot_comparison.py` from `{args.comparison.name}`; it is a view of that CSV, "
             "not a second entry. Cell = final status of the last attempt.", "",
             "| Model | " + " | ".join(cases) + " | Correct |",
             "|---|" + "---|" * len(cases) + "---|"]
    for m in models:
        statuses = [cell[(m, c)]["status"] if (m, c) in cell else "" for c in cases]
        lines.append(f"| `{m}` | " + " | ".join(SHORT.get(s, s or "-") for s in statuses)
                     + f" | {statuses.count('correct')}/{len(cases)} |")
    per_case = ["| Correct models | " + " | ".join(
        str(sum(cell[(m, c)]["status"] == "correct" for m in models if (m, c) in cell)) for c in cases) + " | |"]
    lines += per_case

    wrong = {}
    for c in cases:
        values = Counter(cell[(m, c)]["value_cents"] for m in models
                         if (m, c) in cell and cell[(m, c)]["status"] == "incorrect")
        shared = {v: n for v, n in values.items() if n > 1}
        if shared:
            wrong[c] = shared
    lines += ["", "## Same wrong value returned by several models", ""]
    if wrong:
        for c, shared in wrong.items():
            for v, n in shared.items():
                who = [m for m in models if cell[(m, c)]["status"] == "incorrect" and cell[(m, c)]["value_cents"] == v]
                lines.append(f"- {c}: {n} models return {v} (reference {cell[(who[0], c)]['reference_cents']}): "
                             + ", ".join(f"`{m}`" for m in who))
    else:
        lines.append("- none")
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
