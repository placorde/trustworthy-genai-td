#!/usr/bin/env python3
"""TD2 step 1 (pair A): the small driver that calls `vote_k_sur_n`, and the vote tests.

Run from the repository root (offline, no key, standard library only):
    python td2/vote/vote_driver.py

1. Calls `Orchestrateur.vote_k_sur_n` of kit-td1/skeleton-multi-llm-en.py on the twenty TD1 questions,
   for the fixed 2-of-3 panel and the 3-of-5 quorum, with the last attempt of each member
   (td1/traces-td1.csv). The reference is compared only after the decision.
   Writes td2/vote/vote-table-td1.md.
2. Runs the vote tests (synthetic examples, duplicate route, thresholds, unavailable members, invalid SQL)
   and writes td2/vote/voting-tests-en.csv with the expected and observed decision of each test.
Exits with status 1 if a test fails.
"""
import csv
import importlib.util
import sys
from pathlib import Path
from types import SimpleNamespace

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
PANEL_3 = [("groq", "openai/gpt-oss-120b"), ("openrouter", "cohere/north-mini-code:free"),
           ("groq", "qwen/qwen3.8-27b")]
PANEL_5 = PANEL_3 + [("groq", "openai/gpt-oss-20b"), ("openrouter", "dots-studio/dots-3-note-preview:free")]


def load_vote():
    path = ROOT / "kit-td1" / "skeleton-multi-llm-en.py"
    spec = importlib.util.spec_from_file_location("student_skeleton", path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return lambda proposals, k: module.Orchestrateur.vote_k_sur_n(None, proposals, k)


def last_attempts():
    last = {}
    for r in csv.DictReader(open(ROOT / "td1" / "traces-td1.csv", encoding="utf-8")):
        key = (r["provider"], r["model_requested"], r["case_id"])
        if key not in last or int(r["attempts"]) > int(last[key]["attempts"]):
            last[key] = r
    return last


def proposals_for(last, panel, case):
    """An unavailable or invalid member keeps its place in n but casts no vote."""
    out = []
    for provider, model in panel:
        r = last.get((provider, model, case), {})
        valid = r.get("verdict") in ("correct", "incorrect") and r.get("value", "") != ""
        out.append(SimpleNamespace(provider=provider, model_requested=model,
                                   value=int(r["value"]) if valid else None,
                                   verdict="executed" if valid else "error"))
    return out


def decision_text(d, n):
    return f'{d["value"]} ({d["votes"]}/{n})' if d["consensus"] else f'Abstain (best {d["votes"]}/{n})'


def table(vote):
    last = last_attempts()
    ref = {r["case_id"]: int(r["revenue_cents"])
           for r in csv.DictReader(open(ROOT / "td1" / "reference-td1.csv", encoding="utf-8"))}
    lines = ["# Fixed 2-of-3 panel against 3-of-5 quorum on the twenty TD1 questions", "",
             "Generated by `td2/vote/vote_driver.py` with `vote_k_sur_n` of `kit-td1/skeleton-multi-llm-en.py`.",
             "Fixed panel: gpt-oss-120b (Groq), Cohere north-mini-code (OpenRouter), Qwen 27B (Groq), k = 2.",
             "Quorum: the same three plus gpt-oss-20b (Groq) and Dots (OpenRouter), k = 3. Last attempt per member;",
             "the reference is compared after the decision.", "",
             "| Question | Reference | 2-of-3 | Matches | 3-of-5 | Matches |", "| --- | ---: | --- | --- | --- | --- |"]
    totals = {3: [0, 0, 0], 5: [0, 0, 0]}
    for case in sorted(ref):
        cells = []
        for panel, k in ((PANEL_3, 2), (PANEL_5, 3)):
            d = vote(proposals_for(last, panel, case), k)
            n = len(panel)
            if d["consensus"]:
                ok = d["value"] == ref[case]
                totals[n][0 if ok else 1] += 1
                cells += [decision_text(d, n), "Yes" if ok else "No"]
            else:
                totals[n][2] += 1
                cells += [decision_text(d, n), "—"]
        lines.append(f"| {case} | {ref[case]} | " + " | ".join(cells) + " |")
    lines += ["", f"- **2-of-3**: {totals[3][0]} correct consensuses, {totals[3][1]} incorrect consensuses, "
                  f"{totals[3][2]} abstentions.",
              f"- **3-of-5**: {totals[5][0]} correct consensuses, {totals[5][1]} incorrect consensuses, "
              f"{totals[5][2]} abstentions."]
    (HERE / "vote-table-td1.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return lines


def tests(vote):
    last = last_attempts()

    def p(provider, model, value, verdict="executed"):
        return SimpleNamespace(provider=provider, model_requested=model, value=value, verdict=verdict)

    three = [("groq", "openai/gpt-oss-120b"), ("openrouter", "cohere/north-mini-code:free"), ("groq", "qwen/qwen3.8-27b")]

    def panel(values, members=three):
        return [p(a, b, v) if v is not None else p(a, b, None, "error") for (a, b), v in zip(members, values)]

    cases = [  # (id, nature, description, proposals, k, expected)
        ("T01", "synthetic", "agreement: 100, 100, 120", panel([100, 100, 120]), 2, "100 (2/3)"),
        ("T02", "synthetic", "disagreement: 100, 110, 120", panel([100, 110, 120]), 2, "Abstain (best 1/3)"),
        ("T03", "synthetic", "unavailable: 100, unavailable, unavailable", panel([100, None, None]), 2, "Abstain (best 1/3)"),
        ("T04", "synthetic", "wrong consensus: 0, 0, 100 (reference 100): the vote cannot see it", panel([0, 0, 100]), 2, "0 (2/3)"),
        ("T05", "synthetic", "duplicate route: the same provider and model twice",
         [p("groq", "openai/gpt-oss-120b", 1), p("groq", "openai/gpt-oss-120b", 1), p("groq", "qwen/qwen3.8-27b", 1)], 2, "refused"),
        ("T06", "synthetic", "threshold k = 1 of 3 is not a strict majority", panel([1, 1, 1]), 1, "refused"),
        ("T07", "synthetic", "threshold k = 2 of 4 is not a strict majority",
         panel([1, 1, 1, 1], three + [("groq", "openai/gpt-oss-20b")]), 2, "refused"),
        ("T08", "synthetic", "threshold k = 4 of 3 is above n", panel([1, 1, 1]), 4, "refused"),
        ("T09", "synthetic", "nobody available: abstain with 0 votes", panel([None, None, None]), 2, "Abstain (best 0/3)"),
        ("T10", "synthetic", "an error proposal does not vote even if it carries a value",
         [p("groq", "openai/gpt-oss-120b", 7, "error"), p("openrouter", "cohere/north-mini-code:free", 7, "error"),
          p("groq", "qwen/qwen3.8-27b", 7)], 2, "Abstain (best 1/3)"),
        ("T11", "synthetic", "split 2-2-1 of 5 with k = 3",
         panel([1, 1, 2, 2, 3], PANEL_5), 3, "Abstain (best 2/5)"),
        ("T12", "real", "C17, 3-of-5: Dots returned invalid SQL and stays in n without a vote",
         proposals_for(last, PANEL_5, "C17"), 3, "Abstain (best 1/5)"),
        ("T13", "real", "C02, fixed 2-of-3: Cohere's wrong 0 is outvoted", proposals_for(last, PANEL_3, "C02"), 2, "590320 (2/3)"),
        ("T14", "real", "C02, 3-of-5: 2 votes for 590320, 2 for the shared wrong 0", proposals_for(last, PANEL_5, "C02"), 3, "Abstain (best 2/5)"),
    ]
    rows, failed = [], 0
    for test_id, nature, description, proposals, k, expected in cases:
        try:
            observed = decision_text(vote(proposals, k), len(proposals))
        except ValueError as error:
            observed = f"refused ({error})"
        ok = observed == expected or (expected == "refused" and observed.startswith("refused"))
        failed += not ok
        rows.append({"test_id": test_id, "nature": nature, "description": description, "n": len(proposals), "k": k,
                     "proposals": "; ".join(f"{x.provider}:{x.model_requested}={x.value if x.verdict == 'executed' else x.verdict}"
                                            for x in proposals),
                     "expected": expected, "observed": observed, "pass": "yes" if ok else "no"})
    with open(HERE / "voting-tests-en.csv", "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    return rows, failed


def main():
    vote = load_vote()
    print("\n".join(table(vote)))
    rows, failed = tests(vote)
    print()
    for r in rows:
        print(f'{r["test_id"]} {r["pass"]:3} {r["description"]} -> {r["observed"]}')
    print(f"\n{len(rows) - failed}/{len(rows)} vote tests pass")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
