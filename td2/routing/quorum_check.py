#!/usr/bin/env python3
"""TD2 step 3 (pair C): replay every 2-of-3 panel on the TD1 traces, level by level.

Vote rules from the TD2 lecture: a value counts only if the model returned an executed SQL query
with a value (refused calls and broken SQL stay in n without a vote); one vote per model, final
attempt only; strict majority k = 2 of n = 3; no majority means abstain. Values are integers in
cents, already normalised by the kit. The reference is compared after the decision.
Writes td2/routing/quorum-check-td1.md. Standard library only.
"""
import csv
import itertools
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TD1 = ROOT / "td1"
HERE = Path(__file__).resolve().parent
RATES = json.loads((HERE / "family-rates-td1.json").read_text(encoding="utf-8"))
RULE = json.loads((HERE / "routing-rule.json").read_text(encoding="utf-8"))


def short(m):
    return m.split("/")[-1].replace(":free", "")


def vote(members, case, traces, k=2):
    votes = []
    for m in members:
        t = traces[(m, case)]
        if t["sql"].strip() and t["value"] != "" and t["verdict"] != "sql_invalid":
            votes.append(int(t["value"]))
    if not votes:
        return None, 0
    value, count = Counter(votes).most_common(1)[0]
    return (value, count) if count >= k else (None, count)


def main():
    traces = {}
    for t in csv.DictReader(open(TD1 / "traces-td1.csv", encoding="utf-8")):
        key = (f'{t["provider"]}:{t["model_requested"]}', t["case_id"])
        if key not in traces or int(t["attempts"]) > int(traces[key]["attempts"]):
            traces[key] = t  # keep the final attempt only (six 429 retries in TD1)
    reference = {r["case_id"]: int(r["revenue_cents"]) for r in csv.DictReader(open(TD1 / "reference-td1.csv", encoding="utf-8"))}
    models = list(RATES["models"])
    lines = ["# 2-of-3 panels replayed on the TD1 traces", "",
             "Generated by `td2/routing/quorum_check.py`. Only executed values with their SQL vote, one vote per model",
             "(final attempt), strict majority 2 of 3, abstain otherwise. Panels used by the rule are in bold.", ""]
    summary = {}
    for lv in ("1", "2", "3"):
        cases = RATES["level_cells"][lv]
        chosen = RULE["panels"][f"L{lv}"]["members"]
        lines += [f"## L{lv} cells ({', '.join(cases)})", "",
                  "| Panel | Correct | Abstain | Wrong | Abstained or wrong on |", "|---|---|---|---|---|"]
        for panel in itertools.combinations(models, 3):
            res = Counter()
            bad = []
            for c in cases:
                value, _ = vote(panel, c, traces)
                outcome = "abstain" if value is None else ("correct" if value == reference[c] else "wrong")
                res[outcome] += 1
                if outcome != "correct":
                    bad.append(f"{c} {outcome}")
            name = ", ".join(short(m) for m in panel)
            if set(panel) == set(RULE["panels"]["L3"]["members"]):
                summary.setdefault("L3_panel_by_level", {})[f"L{lv}"] = {
                    "correct": res["correct"], "abstain": res["abstain"], "wrong": res["wrong"], "not_correct": bad}
            if set(panel) == set(chosen):
                name = f"**{name}**"
                summary[f"L{lv}"] = {"members": chosen, "cases": cases, "correct": res["correct"],
                                     "abstain": res["abstain"], "wrong": res["wrong"], "not_correct": bad}
            lines.append(f'| {name} | {res["correct"]} | {res["abstain"]} | {res["wrong"]} | {"; ".join(bad) or "-"} |')
        lines += ["", f"Rule panel L{lv} case by case:", "",
                  "| Question | Values (" + ", ".join(short(m) for m in chosen) + ") | Decision | Reference |", "|---|---|---|---|"]
        for c in cases:
            vals = [traces[(m, c)]["value"] or traces[(m, c)]["verdict"] for m in chosen]
            value, count = vote(chosen, c, traces)
            dec = f"abstain (max {count}/3)" if value is None else f"consensus {value} ({count}/3)"
            lines.append(f"| {c} | {', '.join(vals)} | {dec} | {reference[c]} |")
        lines.append("")
    (HERE / "quorum-check-td1.json").write_text(json.dumps(summary, indent=1) + "\n", encoding="utf-8")
    (HERE / "quorum-check-td1.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
